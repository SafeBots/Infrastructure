"""
Wan 2.2 Runner — Safebox Local Service v1.0

Wraps Alibaba's Wan 2.2 (Apache 2.0) as a Safebox-canonical text-to-video
and image-to-video service. Mixture-of-Experts diffusion model with separate
high-noise and low-noise experts — 27B parameters total, ~14B active per
denoising step, kept VRAM footprint near 14B-class.

Sister runner to ltx-video/. Same /v1/video/generate protocol, different
model behind it. Pick LTX-Video for speed (8-step distilled inference) and
Wan 2.2 for quality (MoE produces sharper detail and better prompt adherence
at the cost of 30-40 step inference).

Endpoints (Safebox canonical):
    POST /v1/video/generate    — text → MP4 (or image+text → MP4)
    GET  /v1/capabilities
    GET  /v1/capacity
    GET  /v1/models
    GET  /health

Models supported via manifests:
  - wan-2-2-ti2v-5b      Combined T2V+I2V, 5B params, ~16GB VRAM with offload
  - wan-2-2-t2v-a14b     T2V only, A14B (27B total, 14B active), 24GB+ VRAM
  - wan-2-2-i2v-a14b     I2V only, A14B, 24GB+ VRAM

Output is MP4 via ffmpeg. Audio is NOT generated by base Wan 2.2 — for
synchronized audio+video, use the ltx-video runner instead. (Wan 2.2-S2V
is a separate audio-driven variant covering speech-to-video; not in this
v1 wrapper.)
"""

