# safebox_auth.py is vendored beside runner.py from model-runners/_shared/
# via sync-shared.sh, and COPYed into /app/ by the Dockerfile.
from safebox_auth import verify_hmac as _sb_verify  # noqa: E402

def verify_hmac(request: Request, body: bytes) -> bool:
    # Canonical HMAC verification lives in ONE place: model-runners/_shared/
    # safebox_auth.py, whose canonical string matches auth.js and the Safebox
    # LocalRunner byte-for-byte. This delegation keeps the call sites unchanged
    # while ensuring every runner shares a single source of truth.
    return _sb_verify(request, body)
def get_capacity_hint() -> str:
    if MAX_QUEUE_DEPTH <= 1:
        return "saturated" if in_flight >= 1 else "available"
    if in_flight >= MAX_QUEUE_DEPTH * 0.9: return "saturated"
    if in_flight >= MAX_QUEUE_DEPTH * 0.7: return "near-saturated"
    return "available"


def safebox_headers(request_id: str, model: str, compute_ms: int = 0
                    ) -> Dict[str, str]:
    return {
        "X-Safebox-Request-Id":    request_id,
        "X-Safebox-Runner-Id":     RUNNER_ID,
        "X-Safebox-Model-Id":      model,
        "X-Safebox-Compute-Ms":    str(compute_ms),
        "X-Safebox-Capacity-Hint": get_capacity_hint(),
    }


def model_matches(requested: str) -> bool:
    if not requested:
        return False
    if requested == MODEL_NAME:
        return True
    if requested == WAN_MODEL_PATH:
        return True
    if "/" in WAN_MODEL_PATH and requested == WAN_MODEL_PATH.rsplit("/", 1)[-1]:
        return True
    return False


def resolve_input_image(input_image: Optional[str]) -> Optional[bytes]:
    if not input_image:
        return None
    if input_image.startswith("data:"):
        try:
            comma = input_image.find(",")
            return base64.b64decode(input_image[comma+1:])
        except Exception as e:
            raise ValueError(f"Bad data: URL: {e}")
    p = Path(input_image)
    if not p.exists():
        raise ValueError(f"inputImage not found: {input_image}")
    return p.read_bytes()


def frames_to_mp4(frames, fps: int, out_path: Path) -> int:
    """Encode a sequence of numpy frames [N, H, W, 3] uint8 into MP4 via
    ffmpeg piping raw frames. Returns the byte size of the written file."""
    import numpy as np
    if not hasattr(frames, "shape"):
        frames = np.asarray(frames)
    if frames.dtype.kind == "f":
        frames = (frames.clip(0, 1) * 255).astype("uint8")
    n, h, w, c = frames.shape
    assert c == 3, f"Expected 3 channels, got {c}"
    cmd = [
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "rawvideo", "-pix_fmt", "rgb24",
        "-s", f"{w}x{h}", "-r", str(fps),
        "-i", "pipe:0",
        "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-preset", "fast", "-crf", "19",
        str(out_path),
    ]
    p = subprocess.run(cmd, input=frames.tobytes(), capture_output=True)
    if p.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {p.stderr.decode('utf-8', errors='replace')}")
    return out_path.stat().st_size


# ─── Wan 2.2 wrapper ───────────────────────────────────────────────────
class WanVideoRunner:
    """Lazily import diffusers + Wan-AI pipeline. Pipeline selection depends
    on WAN_VARIANT — text-to-video, image-to-video, or combined."""

    def __init__(self):
        self.ready    = False
        self.pipeline = None
        self.device   = "cpu"
        self._is_i2v  = False   # whether the loaded pipeline expects an image input

    def load(self):
        if self.ready:
            return
        try:
            import torch
            from diffusers import AutoencoderKLWan
            # Pick the right pipeline class based on the variant
            if WAN_VARIANT == "i2v-a14b":
                from diffusers import WanImageToVideoPipeline  # type: ignore
                pipe_cls = WanImageToVideoPipeline
                self._is_i2v = True
            else:
                # T2V-A14B and TI2V-5B both use WanPipeline (TI2V accepts an
                # optional image at call time)
                from diffusers import WanPipeline  # type: ignore
                pipe_cls = WanPipeline
                self._is_i2v = False
        except Exception as e:
            logger.error(f"Failed to import diffusers Wan pipeline / torch: {e}")
            raise
        logger.info(f"Loading Wan 2.2 — model_path={WAN_MODEL_PATH} variant={WAN_VARIANT}")
        self.device = "cuda" if torch.cuda.is_available() else "cpu"

        vae = AutoencoderKLWan.from_pretrained(
            WAN_MODEL_PATH, subfolder="vae",
            torch_dtype=torch.float32,
        )
        self.pipeline = pipe_cls.from_pretrained(
            WAN_MODEL_PATH, vae=vae,
            torch_dtype=torch.bfloat16 if self.device == "cuda" else torch.float32,
        )

        # CPU offload — Wan A14B variants need this to fit on consumer cards
        if self.device == "cuda" and ENABLE_CPU_OFFLOAD:
            try:
                self.pipeline.enable_model_cpu_offload()
            except Exception as e:
                logger.warning(f"enable_model_cpu_offload failed (continuing): {e}")
                self.pipeline = self.pipeline.to(self.device)
        else:
            self.pipeline = self.pipeline.to(self.device)
        self.ready = True
        logger.info(f"Wan 2.2 ready — device={self.device} i2v_pipeline={self._is_i2v}")

    def generate(self, req: VideoGenerateRequest) -> Dict[str, Any]:
        self.load()
        import torch

        width  = req.width  or DEFAULT_WIDTH
        height = req.height or DEFAULT_HEIGHT
        # Wan 2.2 expects dimensions divisible by 16 (VAE downsample factor)
        width  = (width  // 16) * 16
        height = (height // 16) * 16
        if width <= 0 or height <= 0:
            raise ValueError(f"width and height must be > 0 (got {width}x{height})")

        n_frames = req.numFrames or DEFAULT_NUM_FRAMES
        if n_frames > MAX_NUM_FRAMES:
            raise ValueError(f"numFrames {n_frames} exceeds MAX_NUM_FRAMES {MAX_NUM_FRAMES}")
        if n_frames <= 0:
            raise ValueError("numFrames must be > 0")

        fps              = req.fps               or DEFAULT_FPS
        steps            = req.steps             or DEFAULT_STEPS
        guidance         = req.guidance          or DEFAULT_GUIDANCE
        guidance_low     = req.guidanceLowNoise  or DEFAULT_GUIDANCE_LOW_NOISE
        flow_shift       = req.flowShift         or DEFAULT_FLOW_SHIFT
        seed             = req.seed if req.seed is not None else int.from_bytes(os.urandom(8), "big") % (2**31)

        t0 = time.time()
        source_payload = {
            "prompt": req.prompt, "negativePrompt": req.negativePrompt,
            "width": width, "height": height,
            "numFrames": n_frames, "fps": fps,
            "steps": steps,
            "guidance": guidance, "guidanceLowNoise": guidance_low,
            "flowShift": flow_shift, "seed": seed,
            "hasInputImage": bool(req.inputImage),
        }
        source_sha = hashlib.sha256(
            json.dumps(source_payload, sort_keys=True).encode("utf-8")
        ).hexdigest()

        # Optional input image for I2V (or TI2V combined pipeline)
        init_image = None
        if req.inputImage:
            if not CAP_IMAGE2VIDEO:
                raise ValueError("Image-to-video disabled on this runner")
            from PIL import Image
            init_image = Image.open(io.BytesIO(resolve_input_image(req.inputImage))).convert("RGB")
        elif self._is_i2v:
            raise ValueError("This runner serves an image-to-video Wan variant; inputImage is required.")

        # Tune the scheduler for the resolution (flow_shift)
        try:
            from diffusers.schedulers.scheduling_unipc_multistep import UniPCMultistepScheduler
            self.pipeline.scheduler = UniPCMultistepScheduler.from_config(
                self.pipeline.scheduler.config, flow_shift=flow_shift)
        except Exception as e:
            logger.debug(f"flow_shift configuration skipped: {e}")

        generator = torch.Generator(device=self.device).manual_seed(seed)
        kwargs = {
            "prompt":              req.prompt,
            "negative_prompt":     req.negativePrompt or "",
            "width":               width,
            "height":              height,
            "num_frames":          n_frames,
            "num_inference_steps": steps,
            "guidance_scale":      guidance,
            "generator":           generator,
        }
        # Wan 2.2 MoE — pass the second guidance scale when the pipeline accepts it
        if WAN_VARIANT in ("t2v-a14b", "i2v-a14b"):
            kwargs["guidance_scale_2"] = guidance_low
        if init_image is not None:
            kwargs["image"] = init_image

        with torch.no_grad():
            out = self.pipeline(**kwargs)
        # Wan pipelines return obj.frames[0] (list of PIL images or numpy array)
        frames = out.frames[0] if hasattr(out, "frames") else out
        if isinstance(frames, list):
            import numpy as np
            frames = np.stack([np.asarray(f) for f in frames])
        elif hasattr(frames, "shape") and frames.ndim == 5:
            frames = frames[0].permute(0, 2, 3, 1).cpu().numpy()
        elif hasattr(frames, "cpu"):
            frames = frames.cpu().numpy()

        stem    = (req.filenamePrefix or "safebox-wan-video") + "-" + uuid.uuid4().hex[:12]
        out_path = WORK_DIR / f"{stem}.mp4"
        size_bytes = frames_to_mp4(frames, fps, out_path)
        elapsed_ms = int((time.time() - t0) * 1000)
        video_seconds = n_frames / float(fps)

        output_sha = hashlib.sha256(out_path.read_bytes()).hexdigest()

        result: Dict[str, Any] = {
            "model":  MODEL_NAME,
            "prompt": req.prompt,
            "video": {
                "format":      "mp4",
                "codec":       "h264",
                "width":       width,
                "height":      height,
                "numFrames":   n_frames,
                "fps":         fps,
                "durationSec": round(video_seconds, 3),
                "sizeBytes":   size_bytes,
                "hasAudio":    False,
            },
            "sourceSha256": source_sha,
            "outputSha256": output_sha,
            "usage": {
                "steps":            steps,
                "elapsedMs":        elapsed_ms,
                "realTimeFactor":   round(video_seconds / max(elapsed_ms / 1000.0, 0.001), 3),
                "seed":             seed,
                "guidance":         guidance,
                "guidanceLowNoise": guidance_low,
                "flowShift":        flow_shift,
            },
        }
        if req.outputMode == "base64":
            result["video"]["base64"] = base64.b64encode(out_path.read_bytes()).decode("ascii")
        else:
            result["video"]["path"] = str(out_path)
        return result


